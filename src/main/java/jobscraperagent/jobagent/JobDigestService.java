package jobscraperagent.jobagent;

import jobscraperagent.jobagent.repository.JobRepository;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

@Service
public class JobDigestService {
    private static final Logger log =
            LoggerFactory.getLogger(JobDigestService.class);

    private final JobRepository jobRepository;
    private final JobSearchPreferences preferences;
    private final EmailNotificationService emailService;

    @Value("${spring.mail.username}")
    private String emailAddress;

    public JobDigestService(JobRepository jobRepository, JobSearchPreferences preferences, EmailNotificationService emailService) {
        this.jobRepository = jobRepository;
        this.preferences = preferences;
        this.emailService = emailService;
    }

    @Transactional
    public int sendDigestIfNeeded(){
        int minimumScore = preferences.minimumRelevanceScore();

        List<Job> jobs = jobRepository.findByRelevanceScoreGreaterThanEqualAndNotificationSentAtIsNullOrderByRelevanceScoreDesc(
                minimumScore
        );

        log.info(
                "Preparing job digest: minimumScore={}, eligibleJobs={}",
                minimumScore,
                jobs.size()
        );


        if(jobs.isEmpty()){
            log.info("No eligible jobs; email digest will not be sent.");
            return 0;
        }

        StringBuilder body = new StringBuilder();

        body.append("Your Job Agent found ")
                .append(jobs.size())
                .append(" relevant job(s).\n\n");

        for(Job job : jobs){
            body.append("----------------------------------------\n");
            body.append("Title: ").append(value(job.getTitle())).append("\n");
            body.append("Company: ").append(value(job.getCompany())).append("\n");
            body.append("Location: ").append(value(job.getLocation())).append("\n");
            body.append("Relevance score: ")
                    .append(job.getRelevanceScore()).append("/100\n");

            if(job.getRelevanceExplanation() != null){
                body.append("Why it matches: ")
                        .append(job.getRelevanceExplanation()).append("\n");
            }

            if(job.getPostingUrl() != null && !job.getPostingUrl().isBlank()){
                body.append("Apply / view job: ")
                        .append(job.getPostingUrl()).append("\n");
            }

            if(job.getMatchedTechnologies() != null && !job.getMatchedTechnologies().isBlank()){
                body.append("Matched technologies: ")
                        .append(job.getMatchedTechnologies()).append("\n");
            }

            body.append("\n");
        }

        body.append("\nGenerated by your Job Agent");

        emailService.sendJobDigest(
                "Job Agent: " + jobs.size() + " relevant job(s)",
                body.toString()
        );

        log.info("Job digest email accepted by the configured mail sender.");

        Instant sentAt = Instant.now();

        for(Job job : jobs){
            job.setNotificationSentAt(sentAt);
        }

        jobRepository.saveAll(jobs);
        log.info("Marked {} jobs as notified.", jobs.size());
        return jobs.size();
    }

    private String value(String text){
        return text == null || text.isBlank() ? "Not specified" : text;
    }
}
